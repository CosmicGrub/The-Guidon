/**
 * Counseling wizard (DA 4856) signature-mode picker: verifies the picker's
 * real scope now matches what the UI tells the Soldier.
 *
 * Prior to this fix, "Signature handling" looked like a single control that
 * shaped BOTH export paths - the header text said "Choose how blank
 * signature blocks appear" with no button named, and clicking a non-default
 * mode then "Generate fillable DA 4856" silently produced the exact same
 * bytes as the default mode. The real cause: withSig() stamps `_sigMode`
 * onto the vals object handed to both paths, but pdf456.js's fill() only
 * ever walks Object.keys(F) - the AcroForm field-name map - which has no
 * sigMode entry, so generateFillable() never reads it. printFlatten() DOES
 * read vals._sigMode (js/counselpdf.js, the `sigNote` ternary). Confirmed
 * against the actual embedded form (da4856.clean.pdf via pdf-lib field
 * introspection): the four "...signat[0]" widgets are real PDF /Sig fields
 * (type "unknown" to pdf-lib's getTextField - not text fields), so there's
 * no field-level way to pre-render a note/typed-name under them the way
 * printFlatten()'s HTML can. That's a genuine mechanical limit, not an
 * oversight, so the fix is disclosure (a `.cpdf-scope` note naming exactly
 * which button the picker affects) rather than forcing the fillable path to
 * fake support it doesn't have.
 *
 * This test proves BOTH halves of that claim empirically, not just that the
 * new copy exists:
 *   1. The fillable PDF's actual field content (every F-mapped text field,
 *      plus signature-widget presence) is IDENTICAL across all three
 *      sigModes (real "Generate fillable DA 4856" button, not a direct
 *      fill() call - exercises the exact same code path a Soldier would
 *      hit). Compared at the field level, not raw bytes: pdf-lib's own
 *      doc.save() embeds a save-time-varying trailer entry even when the
 *      content is 100% identical call-to-call, so a full-byte comparison
 *      would be flaky by construction and prove nothing about sigMode.
 *   2. The Print/flatten copy's rendered HTML genuinely DOES change per mode
 *      (via #print-holder, the same technique test-print-paths.mjs uses).
 *   3. The disclosure note is present, reads correctly, and sits between the
 *      mode picker and the two action buttons - not buried where a Soldier
 *      could miss it before clicking either one.
 */
import { chromium } from "playwright";
import { serve } from "./server.mjs";

let fails = 0;
const ok = (m) => console.log("  PASS  " + m);
const bad = (m) => { fails++; console.log("  FAIL  " + m); };

const { server, url } = await serve("web");
const browser = await chromium.launch();
const page = await (await browser.newContext()).newPage();
const noise = [];
page.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") noise.push(m.type() + ": " + m.text()); });
page.on("pageerror", (e) => noise.push("pageerror: " + e.message));

await page.goto(url, { waitUntil: "load" });
await page.waitForTimeout(700);

// Bypass onboarding via a guest session (same pattern as test-mockboard.mjs).
const guestCard = page.locator(".ob-mode-card", { hasText: /guest session/i }).first();
await guestCard.waitFor({ state: "visible", timeout: 8000 }).catch(() => {});
if (await guestCard.count()) {
  await guestCard.click();
  await page.locator("#ob-overlay").waitFor({ state: "detached", timeout: 5000 }).catch(() => {});
}
await page.waitForTimeout(300);

// Load the deferred PDF stack (pdf-lib + the real DA 4856 AcroForm bytes) -
// generateFillable() needs it resident before the "Generate fillable" button
// can produce a real PDF instead of the "PDF engine unavailable" bail-out.
await page.waitForFunction(() => window.G && window.G.pdfAssets && window.G.pdf456);
await page.evaluate(async () => { await window.G.pdfAssets.ensure(); });
const pdfReady = await page.evaluate(() => window.G.pdf456.available());
pdfReady ? ok("PDF engine + DA 4856 form asset loaded (available() = true)") : bad("PDF engine not available after pdfAssets.ensure()");

// Intercept the blob+<a download> pattern util.downloadBinary() uses (see
// test-native-download.mjs) instead of driving Playwright's real download
// machinery - fetch() the blob: URL to recover the actual generated bytes,
// keyed to whichever sigMode was active for that click.
await page.evaluate(() => {
  window.__caps = [];
  // downloadBinary() revokes the object URL 1s after the click (harmless in
  // real use - the browser has already handed the bytes to its download
  // manager by then). Neutralize that here so a slow test runner can never
  // race the revoke against this stub's own fetch() of the same URL.
  URL.revokeObjectURL = function () {};
  const orig = HTMLAnchorElement.prototype.click;
  HTMLAnchorElement.prototype.click = function () {
    const href = this.href;
    if (href && href.indexOf("blob:") === 0) {
      window.__caps.push(
        fetch(href).then((r) => r.arrayBuffer()).then((buf) => {
          const bytes = new Uint8Array(buf);
          let bin = "";
          for (let i = 0; i < bytes.length; i++) bin += String.fromCharCode(bytes[i]);
          return btoa(bin);
        })
      );
      return; // swallow the real click - no download dialog needed for this test
    }
    return orig.call(this);
  };
});

// Open the wizard blank (no starting example) and switch to Single form so
// the "Signature handling" review section (with both action buttons) is on
// screen immediately, without stepping through the wizard.
await page.evaluate(() => { window.G.counselpdf.open(); });
await page.waitForTimeout(300);
await page.locator("button", { hasText: /^Single form$/ }).click();
await page.waitForTimeout(300);

const modalOpen = await page.evaluate(() => !!document.querySelector(".cpdf-backdrop"));
modalOpen ? ok("DA 4856 filler modal opened") : bad("modal did not open");

// A minimal, real header so the generated PDF/printed copy has content.
await page.locator("#cpdf-field-name").fill("Rivera, John A.");
await page.locator("#cpdf-field-rank").fill("SPC");
await page.locator("#cpdf-field-title").fill("SSG Diaz / Squad Leader");

// ---- 1) Disclosure copy: present, correct, and positioned before the buttons ----
const scope = await page.evaluate(() => {
  const sec = Array.from(document.querySelectorAll(".cpdf-review, .cpdf-stage")).find((n) => n.querySelector(".cpdf-scope"));
  if (!sec) return null;
  const note = sec.querySelector(".cpdf-scope");
  const actions = sec.querySelector(".cpdf-actions");
  const sigopts = sec.querySelector(".cpdf-sigopts");
  return {
    text: note.textContent,
    afterPicker: !!(sigopts && (sigopts.compareDocumentPosition(note) & Node.DOCUMENT_POSITION_FOLLOWING)),
    beforeActions: !!(actions && (note.compareDocumentPosition(actions) & Node.DOCUMENT_POSITION_FOLLOWING)),
  };
});
scope && /Print \/ flatten copy only/.test(scope.text)
  ? ok("disclosure note names the Print/flatten copy as the scope")
  : bad("disclosure note missing or wrong text: " + JSON.stringify(scope));
scope && /can't carry preset text/.test(scope.text) && /plain blanks/.test(scope.text)
  ? ok("disclosure note explains the fillable PDF's signature fields stay plain blanks in every mode")
  : bad("disclosure note doesn't explain WHY the fillable path is unaffected: " + JSON.stringify(scope && scope.text));
scope && scope.afterPicker && scope.beforeActions
  ? ok("disclosure note sits between the mode picker and the action buttons - seen before either can be clicked")
  : bad("disclosure note is not positioned between the picker and the buttons: " + JSON.stringify(scope));

// ---- 2) Fillable PDF: identical field content across all three sigModes ----
const SIG_MODES = [
  { label: /Sign on CAC hardware/, id: "cac-note" },
  { label: /^Empty signature fields only$/, id: "bare" },
  { label: /Print typed name under the blank signature line/, id: "typed-name" },
];
for (const m of SIG_MODES) {
  await page.locator("button.cpdf-sigbtn", { hasText: m.label }).click();
  await page.waitForTimeout(100);
  const active = await page.evaluate((id) => {
    const btns = Array.from(document.querySelectorAll("button.cpdf-sigbtn.active"));
    return btns.length === 1;
  }, m.id);
  active ? ok(`sigMode "${m.id}" button shows exactly one active state`) : bad(`sigMode "${m.id}" active-state toggle broken`);

  await page.locator("button", { hasText: /^Generate fillable DA 4856/ }).click();
  await page.waitForFunction(() => /Downloaded the fillable DA 4856/.test(document.querySelector(".cpdf-status")?.textContent || ""), { timeout: 8000 })
    .catch(() => {});
  const status = await page.evaluate(() => document.querySelector(".cpdf-status")?.textContent || "");
  /Downloaded the fillable DA 4856/.test(status)
    ? ok(`sigMode "${m.id}": fillable PDF generated and saved`)
    : bad(`sigMode "${m.id}": fillable generation did not report success - status="${status}"`);
}

const fillableB64 = await page.evaluate(async () => Promise.all(window.__caps));
fillableB64.length === 3
  ? ok("captured all 3 fillable-PDF downloads (one per sigMode)")
  : bad("expected 3 captured downloads, got " + fillableB64.length);

// NOT a raw-byte comparison: confirmed by direct probe (two fill() calls with
// IDENTICAL vals, a beat apart) that pdf-lib's own doc.save() embeds a
// save-time-varying trailer entry (consistent with a fresh document /ID) even
// when nothing about the content changes - so raw bytes differ call-to-call
// regardless of sigMode, and asserting full-byte equality would be flaky by
// construction, not a real regression signal. The actual claim under test is
// that sigMode never reaches the fillable PDF's CONTENT - so reload each
// captured PDF with pdf-lib and compare what's actually IN it: every F-mapped
// text field's value, plus confirmation the 4 signature widgets are still
// present (i.e. structurally untouched, matching fill()'s design - it only
// ever calls setText() for keys in Object.keys(F), which excludes SIG).
const fieldSnapshots = await page.evaluate(async (b64s) => {
  async function extract(b64) {
    const bin = atob(b64);
    const bytes = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
    const L = window.PDFLib || window.pdfLib;
    const doc = await L.PDFDocument.load(bytes);
    const form = doc.getForm();
    const names = form.getFields().map((f) => f.getName());
    const out = {};
    Object.keys(window.G.pdf456.FIELDS).forEach((k) => {
      try { out[k] = form.getTextField(window.G.pdf456.FIELDS[k]).getText() || ""; }
      catch (e) { out[k] = "<error>"; }
    });
    out.__sigFieldsPresent = window.G.pdf456.SIG.every((n) => names.indexOf(n) !== -1);
    return out;
  }
  const results = [];
  for (const b of b64s) results.push(await extract(b));
  return results;
}, fillableB64);

const fieldsJson = fieldSnapshots.map((s) => JSON.stringify(s));
const fieldsIdentical = fieldsJson.length === 3 && fieldsJson[0] === fieldsJson[1] && fieldsJson[1] === fieldsJson[2];
fieldsIdentical
  ? ok("fillable DA 4856's actual field content is IDENTICAL across cac-note/bare/typed-name - the disclosure note's claim holds")
  : bad("fillable DA 4856 field content DIFFERS across sigModes - the disclosure text would be false: " + fieldsJson.join(" | "));
fieldSnapshots.every((s) => s.__sigFieldsPresent === true)
  ? ok("all 4 native signature widgets remain present (structurally untouched) in every sigMode")
  : bad("a signature widget went missing in at least one sigMode: " + JSON.stringify(fieldSnapshots.map((s) => s.__sigFieldsPresent)));

// ---- 3) Print/flatten copy: genuinely DOES change per sigMode ----
await page.evaluate(() => { window.print = () => {}; });

async function printFor(modeLabel) {
  await page.locator("button.cpdf-sigbtn", { hasText: modeLabel }).click();
  await page.waitForTimeout(100);
  await page.locator("button", { hasText: /^Print \/ flatten copy$/ }).click();
  await page.waitForTimeout(300);
  return page.evaluate(() => {
    const h = document.querySelector("#print-holder");
    const html = h ? h.innerHTML : "";
    if (h) h.remove();
    return html;
  });
}

const bareHtml = await printFor(/^Empty signature fields only$/);
const cacHtml = await printFor(/Sign on CAC hardware/);
const typedHtml = await printFor(/Print typed name under the blank signature line/);

// NOTE: the shared <style> block (.sig/.sigline CSS rules) is emitted by
// printFlatten() unconditionally, so "sigline" itself appears in the HTML
// in every mode - only the actual `<div class='sig'>...</div>` markup (or
// its absence) reflects the chosen mode. Check for that, not the CSS text.
const bareSigDivs = (bareHtml.match(/<div class='sig'>/g) || []).length;
bareSigDivs === 0
  ? ok("bare mode: printed copy has no signature-note divs (fields are visually empty, as promised)")
  : bad("bare mode rendered " + bareSigDivs + " signature-note div(s) - should render none: " + bareHtml.slice(0, 300));
/sign on CAC-enabled hardware/i.test(cacHtml)
  ? ok("cac-note mode: printed copy includes the 'sign on CAC-enabled hardware' note")
  : bad("cac-note mode missing its note in the printed copy: " + cacHtml.slice(0, 300));
/Rivera, John A\. \(Counseled\)/.test(typedHtml) && /SSG Diaz \/ Squad Leader \(Counselor\)/.test(typedHtml)
  ? ok("typed-name mode: printed copy shows the typed names under the signature lines")
  : bad("typed-name mode missing typed names in the printed copy: " + typedHtml.slice(0, 400));
const printModesDiffer = bareHtml !== cacHtml && cacHtml !== typedHtml && bareHtml !== typedHtml;
printModesDiffer
  ? ok("Print/flatten output genuinely differs across all three sigModes (this is the path the picker actually controls)")
  : bad("Print/flatten output did not differ across sigModes as expected");

const relevantNoise = noise.filter((n) => !/favicon|Removing XFA form data/.test(n));
relevantNoise.length === 0 ? ok("no unexpected console errors/warnings") : bad("console noise: " + relevantNoise.slice(0, 5).join(" | "));

await browser.close();
await server.close();

console.log(fails ? `\n${fails} FAILURE(S)` : "\nCOUNSELPDF SIGMODE: all passed");
process.exit(fails ? 1 : 0);
