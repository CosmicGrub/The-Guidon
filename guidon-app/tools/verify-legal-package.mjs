#!/usr/bin/env node
/**
 * verify-legal-package: GUIDON_COMMAND_LEGAL_PACKAGE.md as a VERIFIED artifact
 * (AUDIT-2026-09 item K).
 *
 * The Command / Legal / OPSEC review package is the one document GUIDON hands
 * to a commander, a CJA and an S2. Every factual sentence in it is a promise
 * about the running app. Before this tool, nothing tied a sentence to a test,
 * and a wrong one shipped: the package said the roster's "one free-text field"
 * is screened while two more text boxes are not (see LP-058), and for a long
 * time it described a redaction feature that the code no longer had. So now:
 *
 *   1. tools/legal-package-claims.json lists EVERY sentence, clause and table
 *      cell of the document in order, each with a stable id (LP-001 ...).
 *      Each is either
 *        non-factual   an opinion, request, disclaimer, heading or template
 *                      line - with a one-line reason;
 *        factual       and then one of
 *          mechanical    named tests really assert it (proof: [{test, anchor}]);
 *          partial       tests prove part; "gap" says what a human must check;
 *          unverifiable  no repository test can check it (an external citation,
 *                        a release-time fact) - "reason" says why;
 *          contradicted  the running app is measured to disagree with the
 *                        sentence (a known finding). It is reported loudly
 *                        and printed inside the document's own stamp.
 *   2. The static check (the default mode, part of `npm run lint:patterns`,
 *      offline, milliseconds) fails when
 *        - a sentence in the document is not in the map (new or edited text),
 *          or a map entry is no longer in the document (or is out of order);
 *        - a factual claim bundles more than one sentence or clause;
 *        - a named test is not in package.json, not on disk, or no longer
 *          contains the assertion the claim leans on (its "anchor", or, for
 *          the suites written for this tool, the claim's own [LP-nnn] tag);
 *        - the generated stamp block is missing, hand-edited, or was written
 *          for a different version of the document or of the map.
 *   3. `--run` executes every named suite (build first: npm run build) and
 *      checks each claim's proofs. `--run --write-stamp` then regenerates the
 *      stamp block INSIDE the document - version (guidon-app/package.json),
 *      git commit, date, tree state, fingerprints, counts and the ids of what
 *      no test could prove. The stamp is produced only by this tool, only after
 *      every suite passed, and never typed by hand.
 *
 * The stamp is a record of one verification run, not a promise about the
 * future: change the document or the map and the static check fails until the
 * run is repeated. At a release cut, run `--run --write-stamp`; `--release`
 * additionally requires the stamp's version to be the version being cut.
 *
 * This tool never edits the substance of the document: --write-stamp replaces
 * or inserts ONLY the text between the two stamp markers.
 *
 * Usage (from guidon-app/, offline):
 *   node tools/verify-legal-package.mjs                     static check
 *   node tools/verify-legal-package.mjs --report            ... and list every claim no test proves
 *   node tools/verify-legal-package.mjs --run               ... and run the named suites
 *   node tools/verify-legal-package.mjs --run --write-stamp ... and stamp the document
 *   node tools/verify-legal-package.mjs --release           static check + the stamp names the current version
 *   options: --jobs N (suites at once, default 2)  --date YYYY-MM-DD  --root <repo root>
 *            --only <suite key>[,<key>]  (--run for a few suites; cannot be combined with --write-stamp)
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { spawn, spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = path.resolve(HERE, "..", "..");

export const DOC_NAME = "GUIDON_COMMAND_LEGAL_PACKAGE.md";
export const MAP_REL = "guidon-app/tools/legal-package-claims.json";
export const STAMP_START = "<!-- legal-package-stamp:start - generated by guidon-app/tools/verify-legal-package.mjs --write-stamp; do not edit by hand -->";
export const STAMP_END = "<!-- legal-package-stamp:end -->";
const STAMP_BLOCK_RE = /<!-- legal-package-stamp:start[^\n]*-->\r?\n[\s\S]*?<!-- legal-package-stamp:end -->/;
const STAMP_DATA_RE = /<!-- legal-package-stamp-data (\{.*\}) -->/;

export const KINDS = ["factual", "non-factual"];
export const VERIFICATIONS = ["mechanical", "partial", "unverifiable", "contradicted"];
export const UNVERIFIABLE_CLASSES = ["external-citation", "external-legal", "release-time", "process", "human-judgment"];

const sha256 = (text) => createHash("sha256").update(text).digest("hex");
/** A path for a message: relative to the repo root, always with forward slashes (Windows and CI print the same text). */
const rel = (root, file) => path.relative(root, file).split(path.sep).join("/");
const collapse = (s) => String(s).replace(/\s+/g, " ").trim();
const lf = (s) => String(s).replace(/\r\n?/g, "\n");

/* ------------------------------------------------------------------------
   The document as one plain-text stream.

   Markdown decoration (headings, blockquote and list markers, the checkbox
   boxes, table pipes and rules, bold, italics, backticks) is dropped and all
   whitespace collapses to single spaces, so a claim is stored as the words
   the reader sees. Everything inside the generated stamp block, and any
   HTML comment, is not part of the document's substance and is left out.
   The claims must tile this stream in order: the only thing allowed between
   two claims is punctuation and spacing.
   ------------------------------------------------------------------------ */
export function documentStream(md) {
  const text = lf(md).replace(STAMP_BLOCK_RE, "").replace(/<!--[\s\S]*?-->/g, "");
  const out = [];
  for (let line of text.split("\n")) {
    if (/^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)*\|?\s*$/.test(line)) continue; // a table's rule row
    if (/^\s*-{3,}\s*$/.test(line)) continue;                                      // a horizontal rule
    line = line
      .replace(/^\s*#{1,6}\s+/, "")
      .replace(/^\s*(?:>\s?)+/, "")
      .replace(/^\s*(?:[-*+]\s+(?:\[[ xX]\]\s+)?|\d{1,2}\.\s+|[a-z]\.\s+)/, "")
      .replace(/\*+/g, "")
      .replace(/`/g, "");
    if (/^\s*\|/.test(line)) line = line.replace(/^\s*\|/, "").replace(/\|\s*$/, "").replace(/\|/g, " | ");
    if (line.trim()) out.push(line.trim());
  }
  return collapse(out.join(" "));
}

/** Offsets of sentence or clause boundaries INSIDE a claim (outside any
 *  parenthesis or quotation, and not after "U.S."). A factual claim must not
 *  have any: one test must not be able to stand for two sentences. */
export function interiorBoundaries(text) {
  const t = collapse(text);
  const out = [];
  let depth = 0, quoted = false;
  for (let i = 0; i < t.length - 1; i++) {
    const c = t[i];
    if (c === "(") depth++;
    else if (c === ")") depth = Math.max(0, depth - 1);
    else if (c === "\"") quoted = !quoted;
    else if (c === "“") quoted = true;
    else if (c === "”") quoted = false;
    if (depth || quoted) continue;
    if (c === ";" && /\s/.test(t[i + 1])) out.push(i);
    else if ((c === "." || c === "!" || c === "?") && /\s/.test(t[i + 1])) {
      if (/U\.S\.$|U\.S\.C\.$/.test(t.slice(Math.max(0, i - 5), i + 1))) continue;
      if (/^[A-Z“"(]/.test(t.slice(i + 1).trimStart())) out.push(i);
    }
  }
  return out;
}

/** Are the claims, in order, exactly the document's words? */
export function tileClaims(stream, claims, { nextId = null } = {}) {
  const failures = [];
  const hasWords = (s) => /[\p{L}\p{N}]/u.test(s);
  const advice = nextId ? ` - add it to ${MAP_REL} as a new claim (next free id ${nextId}) placed where the text sits: factual with a proof, or non-factual with a reason` : ` - add a claim for it to ${MAP_REL}`;
  let pos = 0;
  for (const c of claims) {
    const t = collapse(c.text);
    const at = stream.indexOf(t, pos);
    if (at === -1) {
      failures.push(`${c.id}: its text is not (or no longer) in the document at this point - edited, moved or removed: "${t.slice(0, 90)}${t.length > 90 ? "..." : ""}"`);
      continue;
    }
    const gap = stream.slice(pos, at);
    if (hasWords(gap)) failures.push(`the document has words no claim covers, just before ${c.id}: "${gap.trim().slice(0, 300)}${gap.trim().length > 300 ? "..." : ""}"${advice}`);
    pos = at + t.length;
  }
  const tail = stream.slice(pos);
  if (hasWords(tail)) failures.push(`the document has words no claim covers after the last claim: "${tail.trim().slice(0, 300)}"${advice}`);
  return failures;
}

/* ------------------------------------------------------------------------
   package.json scripts -> the file a suite runs
   ------------------------------------------------------------------------ */
export function suiteCommand(pkg, key) {
  const cmd = pkg && pkg.scripts && pkg.scripts[key];
  if (typeof cmd !== "string") return null;
  const tokens = cmd.trim().split(/\s+/);
  if (tokens[0] !== "node" || !tokens[1] || !/^tools\/[\w.-]+\.mjs$/.test(tokens[1]) || tokens.some((t) => /^(&&|\|\||;|\|)$/.test(t))) return { key, cmd, file: null };
  return { key, cmd, file: tokens[1], args: tokens.slice(2) };
}

/* ------------------------------------------------------------------------
   Counts, lists and the stamp
   ------------------------------------------------------------------------ */
export function summarize(map) {
  const claims = map.claims || [];
  const by = (v) => claims.filter((c) => c.kind === "factual" && c.verification === v);
  const proofs = claims.reduce((n, c) => n + ((c.proof || []).length), 0);
  const suites = new Set();
  for (const c of claims) for (const p of c.proof || []) suites.add(p.test || p.lint);
  return {
    total: claims.length,
    nonFactual: claims.filter((c) => c.kind === "non-factual").length,
    factual: claims.filter((c) => c.kind === "factual").length,
    mechanical: by("mechanical").length,
    partial: by("partial").length,
    unverifiable: by("unverifiable").length,
    contradicted: by("contradicted").length,
    suites: suites.size,
    proofs,
    ids: {
      partial: by("partial").map((c) => c.id),
      unverifiable: by("unverifiable").map((c) => c.id),
      contradicted: by("contradicted").map((c) => c.id),
    },
  };
}

const idList = (ids) => (ids.length ? ids.join(", ") : "none");

/** The stamp block, a pure function of its fields. */
export function renderStamp(f) {
  const c = f.counts;
  const data = JSON.stringify({
    version: f.version, commit: f.commit, date: f.date, tree: f.tree, docHash: f.docHash, mapHash: f.mapHash,
    result: f.result, counts: { total: c.total, nonFactual: c.nonFactual, factual: c.factual, mechanical: c.mechanical, partial: c.partial, unverifiable: c.unverifiable, contradicted: c.contradicted, suites: c.suites, proofs: c.proofs },
    ids: c.ids,
  });
  return [
    STAMP_START,
    `> **Verification stamp (generated by the verifier, never typed by hand).** Checked against GUIDON **v${f.version}**, commit \`${f.commit}\`, on ${f.date} (working tree: ${f.tree}).`,
    ">",
    `> - **Result: ${f.result}${c.contradicted ? ` with ${c.contradicted} open finding${c.contradicted === 1 ? "" : "s"} (listed below)` : ""}.** All ${c.suites} named test suites passed, and every sentence, clause and table cell of this document is accounted for in \`guidon-app/tools/legal-package-claims.json\`.`,
    `> - **What was proved.** ${c.total} statements in all: ${c.mechanical} factual claims proved by named tests; ${c.partial} factual claims only partly proved by tests (the rest needs a human); ${c.unverifiable} factual claims no repository test can check (external citations and similar - the reason for each is written in the map); ${c.contradicted} factual claim(s) the tests show the running app does not match; and ${c.nonFactual} that are not factual claims (headings, templates, requests, opinions and disclaimers).`,
    `> - **Contradicted by the running app: ${idList(c.ids.contradicted)}.** ${c.contradicted ? "These are open findings, not proofs: the sentence is not true of the app as it runs today." : "Nothing in this document is currently contradicted."}`,
    `> - **Only partly proved: ${idList(c.ids.partial)}.**`,
    `> - **Not checkable by any repository test: ${idList(c.ids.unverifiable)}.**`,
    `> - **Fingerprints.** Document text with this block left out: \`sha256:${f.docHash}\`. Claims map: \`sha256:${f.mapHash}\`. Changing either invalidates this stamp until the verifier is run again.`,
    "> - **Repeat the check:** from `guidon-app/`, after `npm run build`: `node tools/verify-legal-package.mjs --run --write-stamp`.",
    `<!-- legal-package-stamp-data ${data} -->`,
    STAMP_END,
  ].join("\n");
}

/** Insert or replace the stamp block. Nothing else in the document changes. */
export function placeStamp(md, block) {
  const eol = /\r\n/.test(md) ? "\r\n" : "\n";
  const body = block.replace(/\n/g, eol);
  if (STAMP_BLOCK_RE.test(md)) return md.replace(STAMP_BLOCK_RE, () => body);
  const m = /^## /m.exec(md);
  if (!m) throw new Error("cannot place the stamp: the document has no '## ' heading to put it before");
  return md.slice(0, m.index) + body + eol + eol + md.slice(m.index);
}

/* ------------------------------------------------------------------------
   The static check
   ------------------------------------------------------------------------ */
function readText(file) { return lf(readFileSync(file, "utf8")); }

export function verifyLegalPackage({ root = DEFAULT_ROOT, release = false } = {}) {
  const passes = [], failures = [], notes = [];
  const ok = (m) => passes.push(m), bad = (m) => failures.push(m), note = (m) => notes.push(m);
  const APP = path.join(root, "guidon-app");
  const docFile = path.join(root, DOC_NAME);
  const mapFile = path.join(root, MAP_REL);
  const pkgFile = path.join(APP, "package.json");
  const result = { passes, failures, notes, map: null, stream: "", docHash: null, mapHash: null, summary: null, stampData: null, docText: null, pkg: null };

  for (const [what, f] of [["the document", docFile], ["the claims map", mapFile], ["package.json", pkgFile]]) {
    if (!existsSync(f)) { bad(`${what} is missing: ${rel(root, f)}`); }
  }
  if (failures.length) return result;

  const docRaw = readFileSync(docFile, "utf8");
  const mapRaw = readFileSync(mapFile, "utf8");
  let map, pkg;
  try { map = JSON.parse(mapRaw); } catch (e) { bad(`${MAP_REL} is not valid JSON: ${e.message}`); return result; }
  try { pkg = JSON.parse(readFileSync(pkgFile, "utf8")); } catch (e) { bad(`guidon-app/package.json is not valid JSON: ${e.message}`); return result; }
  result.map = map; result.pkg = pkg; result.docText = docRaw;
  const claims = Array.isArray(map.claims) ? map.claims : [];
  const suites = map.suites && typeof map.suites === "object" ? map.suites : {};
  const stream = documentStream(docRaw);
  result.stream = stream;
  result.docHash = sha256(stream);
  result.mapHash = sha256(lf(mapRaw));
  result.summary = summarize(map);
  const S = result.summary;

  /* (a) the map itself is well formed */
  {
    const before = failures.length;
    if (map.document !== DOC_NAME) bad(`(a) the map's "document" is ${JSON.stringify(map.document)}, expected ${JSON.stringify(DOC_NAME)}`);
    const seen = new Set();
    for (const c of claims) {
      const at = c && c.id ? c.id : "(a claim with no id)";
      if (!c || typeof c.id !== "string" || !/^LP-\d{3,}$/.test(c.id)) { bad(`(a) ${at}: ids look like LP-001`); continue; }
      if (seen.has(c.id)) bad(`(a) ${c.id} is used twice`);
      seen.add(c.id);
      if (typeof c.text !== "string" || !collapse(c.text)) { bad(`(a) ${c.id}: no text`); continue; }
      if (!KINDS.includes(c.kind)) { bad(`(a) ${c.id}: kind must be one of ${KINDS.join(" / ")}, not ${JSON.stringify(c.kind)}`); continue; }
      if (c.kind === "non-factual") {
        if (typeof c.reason !== "string" || collapse(c.reason).length < 12) bad(`(a) ${c.id}: a non-factual claim needs a one-line reason saying why it is not a factual claim`);
        if (c.verification || c.proof) bad(`(a) ${c.id}: a non-factual claim carries no verification or proof`);
        continue;
      }
      if (!VERIFICATIONS.includes(c.verification)) { bad(`(a) ${c.id}: a factual claim's verification must be one of ${VERIFICATIONS.join(" / ")}, not ${JSON.stringify(c.verification)}`); continue; }
      const cuts = interiorBoundaries(c.text);
      if (cuts.length) bad(`(a) ${c.id}: a factual claim must be ONE sentence or clause, but this one runs across a boundary (after "${collapse(c.text).slice(Math.max(0, cuts[0] - 25), cuts[0] + 1)}") - split it in the map so each part has its own proof`);
      const proof = Array.isArray(c.proof) ? c.proof : [];
      if (c.verification === "unverifiable") {
        if (proof.length) bad(`(a) ${c.id}: an unverifiable claim names no proof (a proof that does not prove it is worse than none)`);
        if (typeof c.reason !== "string" || collapse(c.reason).length < 30) bad(`(a) ${c.id}: an unverifiable claim needs a written reason (at least a full sentence) saying why no repository test can check it`);
        if (!UNVERIFIABLE_CLASSES.includes(c.class)) bad(`(a) ${c.id}: an unverifiable claim needs a class: ${UNVERIFIABLE_CLASSES.join(" / ")}`);
      } else {
        if (!proof.length) bad(`(a) ${c.id}: a ${c.verification} claim must name at least one proof`);
        if (c.verification === "partial" && (typeof c.gap !== "string" || collapse(c.gap).length < 30)) bad(`(a) ${c.id}: a partial claim needs "gap": what the tests do NOT prove and a human must check`);
        if (c.verification === "contradicted" && (typeof c.finding !== "string" || collapse(c.finding).length < 30)) bad(`(a) ${c.id}: a contradicted claim needs "finding": what the running app does instead`);
        if (c.verification === "mechanical" && (c.gap || c.finding)) bad(`(a) ${c.id}: a mechanical claim has no gap or finding - if part of it is unproven it is "partial"`);
      }
    }
    if (failures.length === before) ok(`(a) the claims map is well formed: ${S.total} statements (${S.factual} factual, ${S.nonFactual} non-factual), ids unique, every factual claim one sentence or clause with a verification, every non-factual one with a reason`);
  }

  /* (b) the claims are exactly the document */
  {
    const top = claims.reduce((n, c) => Math.max(n, Number(/^LP-(\d+)$/.exec((c && c.id) || "")?.[1] || 0)), 0);
    const tile = tileClaims(stream, claims.filter((c) => c && typeof c.text === "string"), { nextId: "LP-" + String(top + 1).padStart(3, "0") });
    tile.forEach((m) => bad("(b) " + m));
    if (!tile.length) ok(`(b) every word of ${DOC_NAME} is inside a claim, in order, and every claim is in the document (fingerprint sha256:${result.docHash.slice(0, 12)}...)`);
  }

  /* (c) every proof names a real test that really contains the assertion */
  {
    const before = failures.length;
    const used = new Set();
    const sourceOf = new Map();
    const source = (file) => { if (!sourceOf.has(file)) sourceOf.set(file, existsSync(file) ? readText(file) : null); return sourceOf.get(file); };
    const lintChain = typeof pkg.scripts?.["lint:patterns"] === "string" ? pkg.scripts["lint:patterns"] : "";
    for (const c of claims) {
      if (!c || c.kind !== "factual" || !Array.isArray(c.proof)) continue;
      c.proof.forEach((p, i) => {
        const at = `${c.id} proof ${i + 1}`;
        if (!p || (!p.test && !p.lint) || (p.test && p.lint)) { bad(`(c) ${at}: a proof names exactly one of "test" (an npm script) or "lint" (a tools/ file in the lint:patterns chain)`); return; }
        let file, key = p.test || p.lint;
        if (p.test) {
          const cmd = suiteCommand(pkg, p.test);
          if (!cmd) { bad(`(c) ${at}: "${p.test}" is not a script in guidon-app/package.json`); return; }
          if (!cmd.file) { bad(`(c) ${at}: package.json's "${p.test}" is not a single 'node tools/<file>.mjs' command (${cmd.cmd.slice(0, 80)})`); return; }
          file = path.join(APP, cmd.file);
        } else {
          if (!/^tools\/[\w.-]+\.mjs$/.test(p.lint)) { bad(`(c) ${at}: a lint proof is a path like tools/lint-x.mjs`); return; }
          file = path.join(APP, p.lint);
          if (!lintChain.includes(p.lint)) bad(`(c) ${at}: ${p.lint} is not in the lint:patterns chain in package.json, so nothing runs it`);
        }
        used.add(key);
        const text = source(file);
        if (text == null) { bad(`(c) ${at}: ${rel(root, file)} does not exist`); return; }
        const meta = suites[key];
        if (!meta || typeof meta.about !== "string" || collapse(meta.about).length < 12) { bad(`(c) ${at}: "${key}" needs an entry in the map's "suites" saying, in a line, what it covers`); return; }
        if (meta.tagged) {
          // an assertion carries its claims in a tag: the literal "[LP-030]" or tag("LP-030", "LP-171") from tools/legal-package-kit.mjs
          if (!new RegExp(`\\[${c.id}\\]|\\btag\\([^)]*["']${c.id}["']`).test(text)) bad(`(c) ${at}: ${key} is a tagged suite but its source has no [${c.id}] assertion - the claim is not really tested`);
          if (p.anchor) bad(`(c) ${at}: a proof to a tagged suite uses the claim's own [${c.id}] tag, not an anchor`);
        } else {
          if (typeof p.anchor !== "string" || collapse(p.anchor).length < 12) { bad(`(c) ${at}: a proof to ${key} names an "anchor" - words from the assertion in the test that proves this (at least 12 characters)`); return; }
          if (!text.includes(p.anchor)) bad(`(c) ${at}: the assertion this claim leans on is gone from ${rel(root, file)} (anchor not found: "${p.anchor.slice(0, 80)}") - the test changed; re-read it and update the claim's proof`);
        }
        if (c.verification === "contradicted" && !meta.tagged) bad(`(c) ${at}: a contradicted claim is pinned by a tagged suite that fails the day the finding stops reproducing`);
      });
    }
    for (const key of Object.keys(suites)) if (!used.has(key)) bad(`(c) the map lists suite "${key}" but no claim uses it`);
    if (failures.length === before) ok(`(c) every proof names a real test (${S.proofs} proofs across ${used.size} suites), each still containing the assertion its claim leans on`);
  }

  /* (d) the generated stamp */
  {
    const before = failures.length;
    const count = docRaw.split(STAMP_START).length - 1;
    const endCount = docRaw.split(STAMP_END).length - 1;
    const m = STAMP_BLOCK_RE.exec(docRaw);
    if (count !== 1 || endCount !== 1 || !m) {
      bad(`(d) ${DOC_NAME} needs exactly one generated verification stamp block (the ${STAMP_START.slice(0, 40)}... markers) - run: node tools/verify-legal-package.mjs --run --write-stamp`);
    } else {
      const found = lf(m[0]);
      const dm = STAMP_DATA_RE.exec(found);
      let data = null;
      try { data = dm ? JSON.parse(dm[1]) : null; } catch (e) { data = null; }
      if (!data) bad("(d) the verification stamp's data line is missing or unreadable - it is generated: run node tools/verify-legal-package.mjs --run --write-stamp");
      else {
        result.stampData = data;
        const want = {
          version: data.version, commit: data.commit, date: data.date, tree: data.tree, docHash: data.docHash, mapHash: data.mapHash, result: data.result,
          counts: Object.assign({}, data.counts, { ids: data.ids }),
        };
        let regenerated = null;
        try { regenerated = lf(renderStamp(want)); } catch (e) { regenerated = null; }
        if (regenerated !== found) bad("(d) the verification stamp was edited by hand (it is not byte-for-byte what the verifier generates from its own data line) - run: node tools/verify-legal-package.mjs --run --write-stamp");
        if (!/^\d+\.\d+\.\d+$/.test(String(data.version))) bad(`(d) the stamp's version ${JSON.stringify(data.version)} is not x.y.z`);
        if (!/^[0-9a-f]{40}$/.test(String(data.commit))) bad(`(d) the stamp's commit ${JSON.stringify(data.commit)} is not a full 40-character git sha`);
        if (!/^\d{4}-\d{2}-\d{2}$/.test(String(data.date))) bad(`(d) the stamp's date ${JSON.stringify(data.date)} is not YYYY-MM-DD`);
        if (data.result !== "PASS") bad(`(d) the stamp's result is ${JSON.stringify(data.result)}; only a PASS is ever written`);
        if (data.docHash !== result.docHash) bad(`(d) ${DOC_NAME} has changed since it was last verified (stamp: sha256:${String(data.docHash).slice(0, 12)}..., now: sha256:${result.docHash.slice(0, 12)}...) - re-run: node tools/verify-legal-package.mjs --run --write-stamp`);
        if (data.mapHash !== result.mapHash) bad(`(d) the claims map has changed since the document was last verified (stamp: sha256:${String(data.mapHash).slice(0, 12)}..., now: sha256:${result.mapHash.slice(0, 12)}...) - re-run: node tools/verify-legal-package.mjs --run --write-stamp`);
        const nowCounts = JSON.stringify([S.total, S.nonFactual, S.factual, S.mechanical, S.partial, S.unverifiable, S.contradicted, S.suites, S.proofs, S.ids]);
        const stCounts = data.counts ? JSON.stringify([data.counts.total, data.counts.nonFactual, data.counts.factual, data.counts.mechanical, data.counts.partial, data.counts.unverifiable, data.counts.contradicted, data.counts.suites, data.counts.proofs, data.ids]) : "";
        if (nowCounts !== stCounts) bad("(d) the counts in the stamp are not the counts the claims map has now");
        if (release && String(data.version) !== String(pkg.version)) bad(`(d) --release: the stamp was written for v${data.version} but this is v${pkg.version} - run the verifier at the cut: node tools/verify-legal-package.mjs --run --write-stamp`);
        if (!release && String(data.version) !== String(pkg.version)) note(`(d) the stamp was written for v${data.version}; this tree is v${pkg.version}. Not a failure (the document has not changed), but the release cut must run: node tools/verify-legal-package.mjs --run --write-stamp   (--release enforces it)`);
        if (data.tree !== "clean") note(`(d) the stamp was written from a working tree with uncommitted changes (${data.tree}); its commit sha does not by itself identify what was tested`);
      }
    }
    if (failures.length === before) ok(`(d) the generated verification stamp is intact and current: v${result.stampData.version}, commit ${result.stampData.commit.slice(0, 12)}, ${result.stampData.date}, result ${result.stampData.result}`);
  }

  if (S.contradicted) note(`OPEN FINDING${S.contradicted === 1 ? "" : "S"} - the running app does not match ${S.contradicted} sentence${S.contradicted === 1 ? "" : "s"} of the package (${S.ids.contradicted.join(", ")}); see "finding" in ${MAP_REL}`);
  note(`${S.partial} claim(s) only partly proved and ${S.unverifiable} no repository test can check - list them with: node tools/verify-legal-package.mjs --report`);
  return result;
}

/** The claims a reviewer must not mistake for tested facts, in full. */
export function reportUnproven(map, sections = ["contradicted", "partial", "unverifiable"]) {
  const lines = [];
  const claims = map.claims || [];
  const short = (s, n = 150) => { const t = collapse(s); return t.length > n ? t.slice(0, n - 1) + "..." : t; };
  const sect = (name, title, list, fmt) => {
    if (!sections.includes(name)) return;
    lines.push(`${title} (${list.length})`);
    if (!list.length) lines.push("  none");
    for (const c of list) lines.push(...fmt(c));
    lines.push("");
  };
  sect("contradicted", "CONTRADICTED BY THE RUNNING APP - open findings", claims.filter((c) => c.verification === "contradicted"), (c) => [`  ${c.id}  "${short(c.text)}"`, `        finding: ${collapse(c.finding)}`]);
  sect("partial", "ONLY PARTLY PROVED - a human must check the rest", claims.filter((c) => c.verification === "partial"), (c) => [`  ${c.id}  "${short(c.text)}"`, `        not proved: ${collapse(c.gap)}`]);
  sect("unverifiable", "NO REPOSITORY TEST CAN CHECK THESE", claims.filter((c) => c.verification === "unverifiable"), (c) => [`  ${c.id}  [${c.class}]  "${short(c.text)}"`, `        why: ${collapse(c.reason)}`]);
  return lines;
}

/* ------------------------------------------------------------------------
   Running the named suites
   ------------------------------------------------------------------------ */
const isSkip = (out) => /\bSKIPPED\b/.test(out);
// A line may carry several tags: "PASS  [LP-026][LP-124] ...".
const TAGS = "(?:\\[LP-\\d{3,}\\])*";
const tagPass = (out, id) => new RegExp(`^\\s*PASS\\s+${TAGS}\\[${id}\\]`, "m").test(out);
const tagFail = (out, id) => new RegExp(`^\\s*FAIL\\s+${TAGS}\\[${id}\\]`, "m").test(out);

function runOne({ root, cmd, timeoutMs }) {
  return new Promise((resolve) => {
    const t0 = Date.now();
    const child = spawn(process.execPath, [cmd.file, ...(cmd.args || [])], { cwd: path.join(root, "guidon-app"), stdio: ["ignore", "pipe", "pipe"], env: process.env });
    let out = "";
    let timedOut = false;
    child.stdout.on("data", (d) => { out += d; });
    child.stderr.on("data", (d) => { out += d; });
    const timer = setTimeout(() => { timedOut = true; child.kill(); }, timeoutMs);
    child.on("close", (code) => { clearTimeout(timer); resolve({ code: timedOut ? null : code, timedOut, out, ms: Date.now() - t0 }); });
    child.on("error", (e) => { clearTimeout(timer); resolve({ code: null, timedOut: false, out: String(e), ms: Date.now() - t0 }); });
  });
}

/** Runs each distinct suite the claims name, then checks each proof.
 *  Returns { suites: {key: {status, ms, out}}, failures: [...] }. */
export async function runProofs({ root = DEFAULT_ROOT, map, pkg, jobs = 2, only = null, timeoutMs = 10 * 60 * 1000, log = () => {} }) {
  const failures = [];
  const keys = [];
  for (const c of map.claims) for (const p of c.proof || []) { const k = p.test || p.lint; if (!keys.includes(k)) keys.push(k); }
  const wanted = only ? keys.filter((k) => only.includes(k)) : keys;
  const results = {};
  const APP = path.join(root, "guidon-app");
  const needsBuild = wanted.some((k) => map.suites[k] && (map.suites[k].needs || []).includes("build"));
  if (needsBuild && !existsSync(path.join(APP, "web", "index.html"))) {
    failures.push("the named suites need a build (guidon-app/web/index.html is missing) - run: npm run build");
    return { suites: results, failures };
  }
  const queue = wanted.slice();
  async function worker() {
    for (;;) {
      const key = queue.shift();
      if (!key) return;
      let cmd;
      if (key.startsWith("test:")) cmd = suiteCommand(pkg, key);
      else cmd = { key, file: key, args: [] };
      if (!cmd || !cmd.file) { results[key] = { status: "fail", ms: 0, out: "" }; failures.push(`${key}: not runnable`); continue; }
      const r = await runOne({ root, cmd, timeoutMs });
      const status = r.timedOut ? "timeout" : r.code !== 0 ? "fail" : isSkip(r.out) ? "skipped" : "pass";
      results[key] = { status, ms: r.ms, out: r.out };
      log(`  ${status === "pass" ? "PASS" : "FAIL"}  ${key} (${(r.ms / 1000).toFixed(1)}s)${status === "pass" ? "" : " - " + (status === "skipped" ? "the suite skipped itself; a suite that skips proves nothing" : status === "timeout" ? "timed out" : "exit code " + r.code)}`);
      if (status !== "pass") {
        const tail = lf(r.out).split("\n").filter((l) => /FAIL|error|Error|SKIP/.test(l)).slice(0, 6).join("\n        ");
        failures.push(`${key}: ${status === "skipped" ? "skipped itself" : status === "timeout" ? "timed out" : "failed (exit " + r.code + ")"}${tail ? "\n        " + tail : ""}`);
      }
    }
  }
  await Promise.all(Array.from({ length: Math.max(1, Math.min(jobs, wanted.length || 1)) }, worker));

  for (const c of map.claims) {
    if (c.kind !== "factual") continue;
    for (const p of c.proof || []) {
      const key = p.test || p.lint;
      const r = results[key];
      if (!r || r.status !== "pass") continue; // already reported (or --only left it out)
      const meta = map.suites[key] || {};
      if (!meta.tagged) continue;
      if (tagFail(r.out, c.id)) failures.push(`${c.id}: ${key} printed a FAIL for its [${c.id}] assertion`);
      else if (!tagPass(r.out, c.id)) failures.push(`${c.id}: ${key} passed but never printed a PASS for its [${c.id}] assertion - the claim was not exercised`);
      else if (c.verification === "contradicted" && !new RegExp(`^\\s*PASS\\s+${TAGS}\\[${c.id}\\][^\\n]*FINDING CONFIRMED`, "m").test(r.out)) failures.push(`${c.id}: ${key} no longer confirms the finding (it should print "FINDING CONFIRMED") - the app or the document changed; re-read the claim and update its verification`);
    }
  }
  return { suites: results, failures };
}

/* ------------------------------------------------------------------------
   git facts for the stamp
   ------------------------------------------------------------------------ */
export function gitFacts(root) {
  const git = (...a) => spawnSync("git", ["-C", root, ...a], { encoding: "utf8" });
  const head = git("rev-parse", "HEAD");
  const commit = head.status === 0 ? head.stdout.trim() : "";
  const st = git("status", "--porcelain");
  const dirty = st.status === 0 ? st.stdout.split("\n").filter((l) => l.trim() && !l.includes(DOC_NAME)) : ["(git unavailable)"];
  return { commit, tree: st.status !== 0 ? "unknown" : dirty.length ? "modified" : "clean" };
}

/* ------------------------------------------------------------------------
   CLI
   ------------------------------------------------------------------------ */
const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const argv = process.argv.slice(2);
  const has = (f) => argv.includes(f);
  const argOf = (f) => { const i = argv.indexOf(f); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith("--") ? argv[i + 1] : null; };
  const KNOWN = ["--run", "--write-stamp", "--release", "--report", "--jobs", "--date", "--root", "--only"];
  const unknown = argv.filter((a) => a.startsWith("--") && !KNOWN.includes(a));
  if (unknown.length) { console.error("verify-legal-package: unknown option " + unknown.join(", ")); process.exit(2); }
  const root = path.resolve(argOf("--root") || DEFAULT_ROOT);
  const run = has("--run"), write = has("--write-stamp");
  const only = argOf("--only") ? argOf("--only").split(",").filter(Boolean) : null;
  if (write && !run) { console.error("verify-legal-package: --write-stamp needs --run - a stamp is only written after the suites have passed"); process.exit(2); }
  if (write && only) { console.error("verify-legal-package: --write-stamp verifies every suite; it cannot be combined with --only"); process.exit(2); }
  const dateArg = argOf("--date");
  if (dateArg && !/^\d{4}-\d{2}-\d{2}$/.test(dateArg)) { console.error("verify-legal-package: --date is YYYY-MM-DD"); process.exit(2); }
  const jobs = Math.max(1, Number(argOf("--jobs")) || 2);

  console.log(`verify-legal-package: every sentence of ${DOC_NAME} maps to a named test or says why it cannot${run ? " (--run: executing the named suites)" : ""}\n`);
  // The stamp is checked LAST and judged again after it is written: a stale stamp is exactly what --run is for, so it
  // never stops the suites from running. Every other static failure does.
  let res = verifyLegalPackage({ root, release: has("--release") });
  const isStamp = (f) => /^\(d\)/.test(f);
  const other = res.failures.filter((f) => !isStamp(f));
  for (const m of res.passes) console.log("  PASS  " + m);
  for (const m of res.notes) console.log("  NOTE  " + m);
  for (const m of other) console.log("  FAIL  " + m);
  const stampFailures = res.failures.filter(isStamp);
  for (const m of stampFailures) console.log(write ? "  NOTE  (before re-stamping) " + m.replace(/^\(d\) /, "") : "  FAIL  " + m);

  let failureCount = other.length + (write ? 0 : stampFailures.length);
  if (res.map && !other.length && run) {
    console.log("");
    const r = await runProofs({ root, map: res.map, pkg: res.pkg, jobs, only, log: (m) => console.log(m) });
    for (const m of r.failures) console.log("  FAIL  " + m);
    failureCount += r.failures.length;
    if (!r.failures.length && !only) console.log(`\n  PASS  all ${res.summary.suites} named suites passed, and every tagged assertion printed its PASS`);
    if (!r.failures.length && write) {
      const g = gitFacts(root);
      if (!/^[0-9a-f]{40}$/.test(g.commit)) { console.log("  FAIL  cannot stamp: no git commit found (is this a git checkout?)"); failureCount++; }
      else {
        const block = renderStamp({ version: res.pkg.version, commit: g.commit, date: dateArg || new Date().toISOString().slice(0, 10), tree: g.tree, docHash: res.docHash, mapHash: res.mapHash, result: "PASS", counts: res.summary });
        writeFileSync(path.join(root, DOC_NAME), placeStamp(res.docText, block), "utf8");
        console.log(`  PASS  --write-stamp: ${DOC_NAME} stamped (v${res.pkg.version}, commit ${g.commit.slice(0, 12)}, working tree ${g.tree})`);
        if (g.tree !== "clean") console.log("  NOTE  the working tree has uncommitted changes, so the stamp says so; commit them first and stamp again for a stamp that names exactly what was tested");
        res = verifyLegalPackage({ root, release: has("--release") });
        for (const m of res.failures) console.log("  FAIL  after stamping: " + m);
        failureCount += res.failures.length;
        if (!res.failures.length) console.log("  PASS  the freshly written stamp passes the static check");
      }
    } else if (!r.failures.length && !write && !only) {
      console.log("  NOTE  the suites passed; to record this in the document run again with --write-stamp");
    }
  } else if (write && other.length) {
    console.log("\n  FAIL  nothing was run and no stamp was written: fix the failures above first");
  }
  if (res.map) {
    if (has("--report") || run) console.log("\n" + reportUnproven(res.map).join("\n"));
    else if (res.summary.contradicted) console.log("\n" + reportUnproven(res.map, ["contradicted"]).join("\n"));
  }

  const S = res.summary;
  console.log("\n" + (failureCount ? `VERIFY-LEGAL-PACKAGE: ${failureCount} FAILURE(S)` : `VERIFY-LEGAL-PACKAGE: all passed${S ? ` (${S.contradicted} contradicted, ${S.partial} partly proved, ${S.unverifiable} not checkable - see NOTE lines)` : ""}`));
  process.exit(failureCount ? 1 : 0);
}
