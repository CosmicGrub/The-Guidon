#!/usr/bin/env node
/**
 * content-manifest: GUIDON's content figures, GENERATED from the one assembled
 * bank and committed as tools/content-manifest.json - so a count is never
 * typed by hand again, a rise is free, and a fall is always a reviewed,
 * recorded decision.
 *
 * Why this exists (2026-09 audit, recommendation D / R35):
 *   - tools/test-consistency.mjs carried FLOORS = { board: 1230, ... } plus
 *     five more typed counts (3632 terms, 164 MOS, 19 creeds ...). Every
 *     content PR had to remember to bump them; PR #183 left main red because
 *     the literal said 1265 and the bank held 1274.
 *   - Nothing noticed a count that FELL by accident. The same audit found the
 *     ESP32 handheld export had silently dropped 61 cards, and three suites
 *     broke in one week on a typed deck size a category merge had changed.
 *   - README.md still said 1,014 cards / 336 doctrine entries long after both
 *     were wrong, because a number in a document is a number nobody reruns.
 *
 * tools/assemble-bank.mjs already produces the one true bank (the static seed
 * plus every numbered content pack, evaluated headlessly in the app's own load
 * order). This tool turns that bank into figures and holds them three ways:
 *
 *   node tools/content-manifest.mjs            LINT (the default; part of
 *       `npm run lint:patterns`). Fails, naming each differing figure, when the
 *       committed manifest is not exactly what the live bank produces, or when
 *       a generated figures block in a document is stale.
 *   node tools/content-manifest.mjs --write    regenerate the manifest and the
 *       document blocks. REFUSES when any total, any board category or any
 *       doctrine topic FELL compared with the committed file ...
 *   ... --write --allow-shrink "<reason>"      ... unless a reason is given, in
 *       which case every drop and the reason are appended to the manifest's
 *       "shrinks" history. The history is append-only.
 *   ... --base <old-manifest.json> | --base-ref <git ref>
 *       the same ratchet for a REVIEW: every figure that fell between that
 *       earlier manifest and the committed one must be named by a shrinks entry
 *       the earlier one does not have, and the earlier history must survive
 *       untouched - so hand-editing the JSON cannot slip a fall past --write.
 *   ... --figures        print the live figures as the Markdown block.
 *   ... --docs-report    advisory: list document lines that quote a count the
 *                        bank disagrees with (never fails).
 *
 * What is ratcheted (may rise freely, may fall only with a recorded reason):
 * totals.*, board.byCategory.*, doctrine.byTopic.*. Everything else in the
 * file (per-pack contributions, per-pillar counts, the seed-only split, the
 * bank fingerprint) is exact but free to move in either direction - a card
 * re-tagged to another pillar, or a pack folded into the seed, loses nothing.
 *
 * Output is deterministic - declared key order for the kinds, code-unit sort
 * for category / topic names, pack files in load order, LF, one trailing
 * newline - so a second --write changes nothing.
 *
 * Stand-ins, so the verifier can itself be verified
 * (tools/test-content-manifest.mjs): --manifest <file>, --seed <index.html>,
 * --modules <dir>, --docs-root <dir>. With any bank or manifest stand-in and no
 * --docs-root, documents are left completely alone: a stand-in bank must never
 * be able to rewrite the real README.
 *
 * Suites and tools import { loadManifest } instead of typing a number.
 */
