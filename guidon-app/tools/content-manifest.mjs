const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
function tally(list, keyOf, order) {
  const m = new Map();
  for (const x of list || []) { const k = String(keyOf(x)); m.set(k, (m.get(k) || 0) + 1); }
  const keys = [...m.keys()];
  if (order) keys.sort((a, b) => { const ia = order.indexOf(a), ib = order.indexOf(b); return (ia === -1 ? 1e9 : ia) - (ib === -1 ? 1e9 : ib) || byCodeUnit(a, b); });
  else keys.sort(byCodeUnit);
  const out = {};
  for (const k of keys) out[k] = m.get(k);
  return out;
}
const pillarOrder = [...PILLARS, UNTAGGED];
const pillarOf = (x) => (x && x.pillar) || UNTAGGED;

/** The figures of an assembled bank (the return value of assembleBank()).
 *  Pure: no clock, no file system, nothing that is not in the bank. */
export function buildFigures(assembled) {
  const d = assembled.data || {};
  const B = (d.board && d.board.questions) || [], D = (d.doctrine && d.doctrine.entries) || [], S = (d.scenarios && d.scenarios.scenarios) || [];
  const totals = {};
  for (const k of KINDS) totals[k.key] = k.count(d);
  const packs = {};
  for (const m of assembled.modules || []) {
    const a = m.added || {};
    // Only packs that contribute records: a zero-content module (a guard, a
    // release note) coming or going is not a content change.
    if ((a.board || 0) || (a.doctrine || 0) || (a.scenarios || 0)) packs[m.file] = { board: a.board || 0, doctrine: a.doctrine || 0, scenarios: a.scenarios || 0 };
  }
  const mosCards = [];
  for (const q of B) for (const m of (Array.isArray(q.mos) ? q.mos : [])) mosCards.push(String(m).toUpperCase());
  const sc = assembled.staticCounts || {};
  return {
    fingerprint: (d.board && typeof d.board.contentHash === "string") ? d.board.contentHash : null,
    totals,
    seedOnly: { board: sc.board || 0, doctrine: sc.doctrine || 0, scenarios: sc.scenarios || 0 },
    packs,
    board: { byCategory: tally(B, (q) => q.category), byPillar: tally(B, pillarOf, pillarOrder), byMos: tally(mosCards, (m) => m) },
    doctrine: { byTopic: tally(D, (e) => e.topic), byPillar: tally(D, pillarOf, pillarOrder) },
    scenarios: { byPillar: tally(S, pillarOf, pillarOrder) },
  };
}

const FIGURE_KEYS = ["fingerprint", "totals", "seedOnly", "packs", "board", "doctrine", "scenarios"];
export const figuresOf = (manifest) => { const o = {}; for (const k of FIGURE_KEYS) o[k] = manifest ? manifest[k] : undefined; return o; };
export const composeManifest = (figures, shrinks) => ({ _about: ABOUT, schema: SCHEMA, ...figuresOf(figures), shrinks: shrinks || [] });
export const serialize = (manifest) => JSON.stringify(manifest, null, 2) + "\n";

const isRatcheted = (p) => p[0] === "totals" || (p[0] === "board" && p[1] === "byCategory") || (p[0] === "doctrine" && p[1] === "byTopic");
const showPath = (p) => p.map((k, i) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? (i ? "." : "") + k : "[" + JSON.stringify(k) + "]")).join("");
function leaves(node, p, out) {
  if (node && typeof node === "object" && !Array.isArray(node)) { for (const k of Object.keys(node)) leaves(node[k], p.concat(k), out); return out; }
  out.set(JSON.stringify(p), { path: p, value: node });
  return out;
}

/** Every figure that differs between two manifests (or figure sets), each as
 *  { figure, path, from, to, ratcheted, fell }. `fell` is true only for a
 *  ratcheted figure that went down or vanished. */
export function diffFigures(before, after) {
  const a = leaves(figuresOf(before), [], new Map()), b = leaves(figuresOf(after), [], new Map());
  const out = [];
  for (const key of new Set([...a.keys(), ...b.keys()])) {
    const x = a.get(key), y = b.get(key);
    const from = x ? x.value : undefined, to = y ? y.value : undefined;
    if (from === to) continue;
    const p = (x || y).path, ratcheted = isRatcheted(p);
    const fell = ratcheted && typeof from === "number" && from > 0 && (to === undefined || (typeof to === "number" && to < from));
    out.push({ figure: showPath(p), path: p, from, to, ratcheted, fell });
  }
  return out.sort((m, n) => byCodeUnit(m.figure, n.figure));
}

const num = (v) => (typeof v === "number" ? v.toLocaleString("en-US") : JSON.stringify(v));
/** One differing figure, in plain words. */
export function describeDiff(x) {
  if (x.from === undefined) return `${x.figure}: not in the committed manifest, the live bank has ${num(x.to)}`;
  if (x.to === undefined) return `${x.figure}: the committed manifest says ${num(x.from)}, the live bank no longer has it${x.fell ? " (FELL to nothing)" : ""}`;
  if (typeof x.from === "number" && typeof x.to === "number") return `${x.figure}: the committed manifest says ${num(x.from)}, the live bank has ${num(x.to)} (${x.to > x.from ? "up " + num(x.to - x.from) : (x.fell ? "FELL by " : "down ") + num(x.from - x.to)})`;
  return `${x.figure}: the committed manifest says ${num(x.from)}, the live bank has ${num(x.to)}${x.figure === "fingerprint" ? " (a card was added, removed or reworded)" : ""}`;
}

/** Throws, in plain words, on a manifest nobody should trust. */
export function validateManifest(m, label = MANIFEST_REL) {
  if (!m || typeof m !== "object" || Array.isArray(m)) throw new Error(`${label}: expected a JSON object`);
  if (m.schema !== SCHEMA) throw new Error(`${label}: schema is ${JSON.stringify(m.schema)}, this tool writes schema ${SCHEMA}`);
  if (!m.totals || typeof m.totals !== "object") throw new Error(`${label}: has no "totals"`);
  if (!m.board || !m.board.byCategory) throw new Error(`${label}: has no "board.byCategory"`);
  if (!Array.isArray(m.shrinks)) throw new Error(`${label}: "shrinks" must be a list (an empty one when nothing has ever been removed)`);
  m.shrinks.forEach((e, i) => {
    const at = `${label}: shrinks[${i}]`;
    if (!e || typeof e.reason !== "string" || e.reason.trim().length < MIN_REASON) throw new Error(`${at} needs a real "reason" (${MIN_REASON}+ characters)`);
    if (typeof e.date !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(e.date)) throw new Error(`${at} needs a "date" (YYYY-MM-DD)`);
    if (!Array.isArray(e.drops) || !e.drops.length) throw new Error(`${at} records no drops`);
    for (const d of e.drops) if (!d || typeof d.figure !== "string" || typeof d.from !== "number" || typeof d.to !== "number" || !(d.to < d.from)) throw new Error(`${at} has a drop that is not { figure, from, to } with to < from: ${JSON.stringify(d)}`);
  });
  return m;
}

/** The committed manifest, for suites and tools that need a figure. */
export function loadManifest(file = MANIFEST_PATH) {
  let text;
  try { text = readFileSync(file, "utf8"); } catch (e) { throw new Error(`content manifest not found at ${file} - run: node tools/content-manifest.mjs --write`); }
  let parsed;
  try { parsed = JSON.parse(text); } catch (e) { throw new Error(`${file} is not valid JSON (${e.message}) - an unresolved merge? Take either side, then run: node tools/content-manifest.mjs --write`); }
  return validateManifest(parsed, file);
}

/** The review ratchet: what fell between an EARLIER manifest and this one
 *  without being recorded. Returns a list of plain-word problems. */
export function unrecordedFalls(base, committed) {
  const problems = [];
  const bs = Array.isArray(base.shrinks) ? base.shrinks : [], cs = Array.isArray(committed.shrinks) ? committed.shrinks : [];
  if (JSON.stringify(cs.slice(0, bs.length)) !== JSON.stringify(bs)) problems.push(`the shrinks history was rewritten: the earlier manifest's ${bs.length} entr${bs.length === 1 ? "y" : "ies"} must still be there, first and unchanged (the history only grows)`);
  const recorded = new Set();
  for (const e of cs.slice(bs.length)) for (const d of e.drops || []) recorded.add(d.figure);
  for (const x of diffFigures(base, committed)) if (x.fell && !recorded.has(x.figure)) problems.push(`${x.figure} fell from ${num(x.from)} to ${x.to === undefined ? "nothing" : num(x.to)} with no shrinks entry recording why - regenerate with: node tools/content-manifest.mjs --write --allow-shrink "<reason>"`);
  return problems;
}

/* ------------------------------------------------------------------------
   Documents: one generated block, and an advisory report.
   ------------------------------------------------------------------------ */
export function figuresBlock(fig) {
  const t = fig.totals;
  const rows = [];
  for (const k of KINDS) {
    if (!k.label) continue;
    let v = num(t[k.key]);
    if (k.key === "board") v += ` in ${num(t.boardCategories)} categories`;
    if (k.key === "doctrine") v += ` in ${num(t.doctrineTopics)} topics`;
    rows.push(`| ${k.label} | ${v} |`);
  }
  return [BLOCK_START, "| Content | Live figure |", "|---|---|", ...rows, BLOCK_END].join("\n");
}

const QUOTED = "(\\d{1,3}(?:,\\d{3})+|\\d{2,5})";
const DOC_PATTERNS = [
  { key: "board", re: new RegExp("\\b" + QUOTED + "\\s+(?:remaining\\s+)?board(?:\\s+study)?\\s+(?:cards|questions|prompts)\\b", "gi") },
  { key: "board", re: new RegExp("\\bBoard study cards\\s*\\|\\s*" + QUOTED, "gi") },
  { key: "acronyms", re: new RegExp("\\b" + QUOTED + "(?:-term\\b|\\s+(?:total\\s+)?(?:acronyms?|terms)\\b)", "gi") },
  { key: "doctrine", re: new RegExp("\\b" + QUOTED + "\\s+doctrine\\s+entries\\b", "gi") },
  { key: "doctrine", re: new RegExp("\\bDoctrine entries\\s*\\|\\s*" + QUOTED, "gi") },
  { key: "scenarios", re: new RegExp("\\b" + QUOTED + "\\s+scenarios\\b", "gi") },
  { key: "scenarios", re: new RegExp("\\bScenarios\\s*\\|\\s*" + QUOTED, "gi") },
  { key: "mos", re: new RegExp("\\b" + QUOTED + "\\s+MOS(?:s|\\s+entries)\\b", "g") },
  { key: "mos", re: new RegExp("\\bMOS entries\\s*\\|\\s*" + QUOTED, "gi") },
];
/** Lines of a document (outside its generated block) that quote a count the
 *  bank disagrees with: [{ line, key, quoted, live, text }]. */
export function docDisagreements(text, fig) {
  const body = text.replace(BLOCK_RE, (m) => m.replace(/[^\n]/g, " "));
  const out = [];
  body.split("\n").forEach((line, i) => {
    for (const { key, re } of DOC_PATTERNS) {
      re.lastIndex = 0;
      for (const m of line.matchAll(re)) {
        const quoted = Number(m[1].replace(/,/g, ""));
        if (quoted !== fig.totals[key]) out.push({ line: i + 1, key, quoted, live: fig.totals[key], text: line.trim().replace(/\s+/g, " ").slice(0, 110) });
      }
    }
  });
  return out;
}

