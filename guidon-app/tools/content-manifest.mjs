if (path.basename(process.argv[1] || "") === "content-manifest.mjs") main();

function main() {
  const argv = process.argv.slice(2);
  const has = (f) => argv.includes(f);
  const argOf = (f) => { const i = argv.indexOf(f); return i !== -1 && argv[i + 1] !== undefined && !argv[i + 1].startsWith("--") ? argv[i + 1] : null; };
  const KNOWN = ["--write", "--allow-shrink", "--manifest", "--seed", "--modules", "--docs-root", "--base", "--base-ref", "--figures", "--docs-report", "--help"];
  let fails = 0;
  const ok = (m) => console.log("  PASS  " + m);
  const bad = (m) => { fails++; console.log("  FAIL  " + m); };
  const finish = () => { console.log("\n" + (fails ? `CONTENT-MANIFEST: ${fails} FAILURE(S)` : "CONTENT-MANIFEST: all passed")); process.exit(fails ? 1 : 0); };

  if (has("--help")) { console.log(readFileSync(fileURLToPath(import.meta.url), "utf8").split("*/")[0].replace(/^#!.*\n/, "")); process.exit(0); }
  const unknown = argv.filter((a) => a.startsWith("--") && !KNOWN.includes(a));
  const WRITE = has("--write");
  const manifestPath = argOf("--manifest") ? path.resolve(argOf("--manifest")) : MANIFEST_PATH;
  const standIn = !!(argOf("--manifest") || argOf("--seed") || argOf("--modules"));
  const docsRoot = argOf("--docs-root") ? path.resolve(argOf("--docs-root")) : (standIn ? null : REPO);
  const shown = standIn ? manifestPath : MANIFEST_REL;

  console.log("content-manifest: the committed content figures vs the live assembled bank" + (WRITE ? " (--write)" : "") + "\n");
  if (unknown.length) { bad(`unknown option ${unknown.join(", ")} (known: ${KNOWN.join(" ")})`); finish(); }

  /* ---- the live bank ---- */
  const bankOpts = {};
  if (argOf("--seed")) bankOpts.seedPath = path.resolve(argOf("--seed"));
  if (argOf("--modules")) bankOpts.moduleDir = path.resolve(argOf("--modules")) + path.sep;
  let assembled;
  try { assembled = assembleBank(bankOpts); } catch (e) { bad("the bank could not be assembled: " + e.message); finish(); }
  const broken = assembled.modules.filter((m) => m.error);
  if (broken.length) { bad(`content pack(s) failed to load, so every figure would come out short - nothing compared, nothing written: ${broken.map((m) => m.file + " (" + m.error + ")").join("; ")}`); finish(); }
  const live = buildFigures(assembled);
  if (!live.fingerprint) { bad("the assembled bank carries no fingerprint (board.contentHash) - 98-content-pack-finalize.js did not run"); finish(); }
  ok(`assembled the live bank: ${num(live.totals.board)} board cards in ${num(live.totals.boardCategories)} categories, ${num(live.totals.doctrine)} doctrine entries, ${num(live.totals.scenarios)} scenarios, ${num(live.totals.acronyms)} dictionary terms (${Object.keys(live.packs).length} contributing packs, fingerprint ${live.fingerprint})`);

  if (has("--figures")) { console.log("\n" + figuresBlock(live) + "\n"); process.exit(0); }

  if (has("--docs-report")) {
    let lines = 0;
    for (const rel of REPORT_DOCS) {
      const file = path.join(docsRoot || REPO, rel);
      if (!existsSync(file)) continue;
      const hits = docDisagreements(readFileSync(file, "utf8"), live);
      lines += hits.length;
      console.log(`\n  ${rel}: ${hits.length ? hits.length + " line(s) quote a count the bank disagrees with" : "no quoted count disagrees with the bank"}${HISTORY_DOCS.has(rel) && hits.length ? "  (a session history: these are as-of-then figures, listed for information - do not rewrite history)" : ""}`);
      for (const h of hits) console.log(`    line ${h.line}: says ${num(h.quoted)} ${h.key}, the bank has ${num(h.live)}   | ${h.text}`);
    }
    console.log(`\n  ${lines} line(s) in all. Advisory only - never type the new number in; quote the generated block (node tools/content-manifest.mjs --figures) or drop the number.`);
    process.exit(0);
  }

  /* ---- the committed manifest ---- */
  let committed = null, committedText = null;
  if (existsSync(manifestPath)) {
    committedText = readFileSync(manifestPath, "utf8");
    try { committed = validateManifest(JSON.parse(committedText), shown); }
    catch (e) { bad(`${e.message.startsWith(shown) ? e.message : shown + " is not valid JSON (" + e.message + ") - an unresolved merge? Take either side, then run --write again"}${WRITE ? " - nothing written" : ""}`); finish(); }
  }

  /* ---- --write ---- */
  if (WRITE) {
    const reasonGiven = has("--allow-shrink");
    const reason = (argOf("--allow-shrink") || "").trim();
    const falls = committed ? diffFigures(committed, live).filter((x) => x.fell) : [];
    if (reasonGiven && reason.length < MIN_REASON) { bad(`--allow-shrink needs the reason in quotes, ${MIN_REASON}+ characters saying why the content was removed - nothing written`); finish(); }
    if (falls.length && !reasonGiven) {
      for (const x of falls) bad(describeDiff(x));
      console.log(`\n  REFUSED, nothing written: ${falls.length} figure(s) FELL. If content went missing by accident, find out where it went.\n  If it was removed on purpose, say why and it will be recorded:\n    node tools/content-manifest.mjs --write --allow-shrink "<reason>"`);
      finish();
    }
    const shrinks = committed ? committed.shrinks.slice() : [];
    if (falls.length) {
      let appVersion = null;
      try { appVersion = JSON.parse(readFileSync(path.join(APP, "package.json"), "utf8")).version || null; } catch (e) { /* stand-in tree */ }
      shrinks.push({ date: new Date().toISOString().slice(0, 10), appVersion, reason, drops: falls.map((x) => ({ figure: x.figure, from: x.from, to: x.to === undefined ? 0 : x.to })) });
    } else if (reasonGiven) console.log("  note  nothing fell, so --allow-shrink was not needed and nothing was recorded");
    const next = serialize(composeManifest(live, shrinks));
    if (next === committedText) ok(`--write: ${shown} already up to date, nothing written`);
    else {
      const existed = committedText !== null;
      writeFileSync(manifestPath, next, "utf8");
      committedText = next; committed = JSON.parse(next);
      ok(`--write: ${existed ? "rewrote" : "created"} ${shown}${falls.length ? ` and recorded ${falls.length} drop(s): "${reason}"` : ""}`);
    }
    for (const rel of docsRoot ? FIGURE_DOCS : []) {
      const file = path.join(docsRoot, rel);
      if (!existsSync(file)) continue;
      const text = readFileSync(file, "utf8");
      if (!BLOCK_RE.test(text)) continue; // reported by the lint below
      const nextText = text.replace(BLOCK_RE, () => figuresBlock(live));
      if (nextText === text) ok(`--write: the figures block in ${rel} is already up to date`);
      else { writeFileSync(file, nextText, "utf8"); ok(`--write: regenerated the figures block in ${rel}`); }
    }
  }

  /* ---- lint ---- */
  if (!committed) { bad(`${shown} does not exist - create it: node tools/content-manifest.mjs --write`); finish(); }
  const diffs = diffFigures(committed, live);
  if (diffs.length === 0 && committedText === serialize(composeManifest(live, committed.shrinks))) {
    ok(`${shown} is exactly what the live bank produces (${leaves(figuresOf(live), [], new Map()).size} figures; ${committed.shrinks.length} recorded shrink(s))`);
  } else if (diffs.length === 0) {
    bad(`${shown} holds the right figures but is not byte-for-byte what --write generates (hand-edited, re-ordered or re-indented) - run: node tools/content-manifest.mjs --write`);
  } else {
    const SHOW = 40;
    diffs.slice(0, SHOW).forEach((x) => bad(describeDiff(x)));
    if (diffs.length > SHOW) { fails += diffs.length - SHOW; console.log(`  FAIL  ... and ${diffs.length - SHOW} more differing figure(s)`); }
    const fell = diffs.filter((x) => x.fell).length;
    console.log(`\n  ${shown} is stale: ${diffs.length} figure(s) differ from the live bank${fell ? `, ${fell} of them FELL` : ""}. Regenerate it in the same change:\n    node tools/content-manifest.mjs --write${fell ? ' --allow-shrink "<why this content was removed>"' : ""}`);
  }

  /* ---- review ratchet against an earlier manifest ---- */
  let base = null, baseLabel = null;
  if (argOf("--base")) {
    baseLabel = argOf("--base");
    try { base = validateManifest(JSON.parse(readFileSync(path.resolve(baseLabel), "utf8")), baseLabel); } catch (e) { bad(`--base: ${e.message}`); }
  } else if (argOf("--base-ref")) {
    const ref = argOf("--base-ref");
    baseLabel = `${ref}:${MANIFEST_REL}`;
    const git = (...a) => spawnSync("git", a, { cwd: REPO, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
    if (git("rev-parse", "--verify", "--quiet", ref + "^{commit}").status !== 0) bad(`--base-ref: git cannot find "${ref}" here (a shallow checkout? fetch it first) - the ratchet was NOT checked`);
    else {
      const shownAt = git("show", baseLabel);
      if (shownAt.status !== 0) ok(`--base-ref: ${ref} has no ${MANIFEST_REL} yet, so there is nothing earlier to ratchet against`);
      else { try { base = validateManifest(JSON.parse(shownAt.stdout), baseLabel); } catch (e) { bad(`--base-ref: ${e.message}`); } }
    }
  }
  if (base) {
    const problems = unrecordedFalls(base, committed);
    if (problems.length === 0) ok(`ratchet vs ${baseLabel}: nothing fell without a recorded reason, and the earlier shrinks history is intact`);
    else problems.forEach((p) => bad(`ratchet vs ${baseLabel}: ${p}`));
  }

  /* ---- generated blocks in documents ---- */
  if (docsRoot) {
    for (const rel of FIGURE_DOCS) {
      const file = path.join(docsRoot, rel);
      if (!existsSync(file)) { bad(`${rel} is listed in FIGURE_DOCS but does not exist`); continue; }
      const m = readFileSync(file, "utf8").match(BLOCK_RE);
      if (!m) bad(`${rel} has lost its generated figures block (the ${BLOCK_END.replace("end", "start / end")} markers) - put the markers back and run: node tools/content-manifest.mjs --write`);
      else if (m[0].replace(/\r\n/g, "\n") === figuresBlock(live)) ok(`the generated figures block in ${rel} matches the live bank`);
      else bad(`the generated figures block in ${rel} is stale - run: node tools/content-manifest.mjs --write`);
    }
  }
  console.log(`\n  live figures, any time: node tools/content-manifest.mjs --figures   (never type a count into a suite or a document - import { loadManifest } from tools/content-manifest.mjs, or quote the generated block; documents that still quote a stale number: --docs-report)`);
  finish();
}
