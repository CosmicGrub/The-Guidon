/**
 * --ink-* static fallbacks (collective roadmap Q11, engine floor) and the
 * boot notice for engines below it.
 *
 * The five --ink-* text tokens are the app's contrast guarantee for
 * accent-coloured text: html { --ink-amber: color-mix(in srgb, var(--amber)
 * 60%, var(--text) 40%) } (src/index.html). color-mix() is exactly the
 * engine floor (Chromium 111 / WebKit 16.2 / Gecko 113, tools/engine-
 * floor.json); below it the token computes to nothing and every accent-
 * coloured line of text falls back to inherited colour. tools/build.mjs
 * therefore GENERATES, into web/ and dist/, one static #rrggbb per theme
 * per token - the same 60/40 sRGB blend, precomputed from that theme's own
 * tokens - inside `@supports not (color: color-mix(in srgb, red, blue))`.
 *
 * WHY @supports AND NOT TWO DECLARATIONS IN THE THEME BLOCK (the parity
 * design's first idea: `--ink-amber: #hex; --ink-amber: color-mix(...)`,
 * "engines without color-mix keep the static one"): a custom property is
 * never invalid at parse time - any token stream is a valid value - so the
 * later declaration wins on EVERY engine and the static one is simply
 * discarded; only a `color:` property gets declaration-level fallback.
 * Part (e) below measures that in Chromium rather than asserting it.
 *
 * Parts (one browser; lint-ci-matrix counts launch( calls):
 *   (a) Node: web/index.html carries the generated block - exactly one
 *       @supports-not block holding one html { } base rule plus one
 *       html[data-theme="<id>"] rule per registry theme (24), five static
 *       #rrggbb --ink-* declarations each; the ids equal the THEMES
 *       registry; dist/guidon-standalone.html carries the identical block;
 *       the existing html { --ink-*: color-mix(...) } rule is still there.
 *   (b) Chromium, 3 themes: getComputedStyle(html).getPropertyValue(
 *       "--ink-amber") is the color-mix form, never a static hex - the
 *       cascade leaves the real token in charge on an engine at the floor.
 *   (c) Node: the blend recomputed INDEPENDENTLY of build.mjs - the browser
 *       resolves --amber/--green/--red/--cyan/--violet/--text for every
 *       theme through the real cascade (:root, html.light, the theme
 *       block), Node blends round(.6*accent + .4*text) per channel - must
 *       match the generated static hex within 1 per channel, all 24 x 5.
 *   (d) Chromium, all 24 themes: an element coloured var(--ink-<x>) renders
 *       (getComputedStyle().color, the engine's own color-mix result) within
 *       1 per channel of the static hex - the formula matches the engine.
 *   (e) the measurement behind the @supports decision (see above).
 *   (f) boot notice: a page whose CSS.supports() denies color-mix (stubbed
 *       via addInitScript before load) shows the one-line util.toast notice
 *       naming the engine floor after boot; an unstubbed page never does.
 */
import { chromium } from "playwright";
import { readFile } from "node:fs/promises";
import { serve } from "./server.mjs";
import { deriveThemeIds } from "./build.mjs";
import { dismissOnboarding } from "./dismiss-onboarding.mjs";

let fails = 0;
const ok = (m) => console.log("  PASS  " + m);
const bad = (m) => { fails++; console.log("  FAIL  " + m); };

const TOKENS = ["amber", "green", "red", "cyan", "violet"];
const SUPPORTS_HEAD = "@supports not (color: color-mix(in srgb, red, blue)) {";
const MARKER = "/* ==== --ink-* static fallbacks (generated by tools/build.mjs";

const web = await readFile("web/index.html", "utf8");
const dist = await readFile("dist/guidon-standalone.html", "utf8");
const src = await readFile("src/index.html", "utf8");
const registryIds = deriveThemeIds(src).ids;

/* ---- (a) the generated block, parsed from the built output ---- */
function parseBlock(html, label) {
  const at = html.indexOf(MARKER);
  if (at < 0) { bad(`(a) ${label}: generated --ink-* fallback block marker is missing`); return null; }
  if (html.indexOf(MARKER, at + 1) >= 0) { bad(`(a) ${label}: fallback marker appears more than once`); return null; }
  const head = html.indexOf(SUPPORTS_HEAD, at);
  if (head < 0) { bad(`(a) ${label}: no "${SUPPORTS_HEAD}" after the marker`); return null; }
  // brace-match the @supports body
  let depth = 0, close = -1;
  for (let i = html.indexOf("{", head); i < html.length; i++) {
    if (html[i] === "{") depth++;
    else if (html[i] === "}") { depth--; if (depth === 0) { close = i; break; } }
  }
  if (close < 0) { bad(`(a) ${label}: @supports block never closes`); return null; }
  const body = html.slice(html.indexOf("{", head) + 1, close);
  const rules = {};
  let base = null;
  const ruleRe = /^\s*(html(?:\[data-theme="([a-z0-9-]+)"\])?)\s*\{([^}]*)\}/gm;
  let m;
  while ((m = ruleRe.exec(body))) {
    const decls = {};
    for (const d of m[3].matchAll(/--ink-([a-z]+)\s*:\s*(#[0-9a-f]{6})\s*;/g)) decls[d[1]] = d[2];
    if (m[2]) rules[m[2]] = decls; else base = decls;
  }
  return { body, rules, base, text: html.slice(at, close + 1) };
}
const webBlock = parseBlock(web, "web/index.html");
const distBlock = parseBlock(dist, "dist/guidon-standalone.html");
if (webBlock) {
  const ids = Object.keys(webBlock.rules);
  const complete = ids.filter((id) => TOKENS.every((t) => /^#[0-9a-f]{6}$/.test(webBlock.rules[id][t] || "")));
  ids.length === 24 && complete.length === 24
    ? ok(`(a) web/index.html: 24 theme rules inside the @supports-not block, 5 static #rrggbb --ink-* declarations each`)
    : bad(`(a) web/index.html: ${ids.length} theme rules, ${complete.length} with all 5 static declarations (want 24/24)`);
  const missing = registryIds.filter((id) => !ids.includes(id));
  const extra = ids.filter((id) => !registryIds.includes(id));
  !missing.length && !extra.length
    ? ok(`(a) fallback theme ids equal the THEMES registry (${registryIds.length} ids)`)
    : bad(`(a) fallback ids vs THEMES registry - missing: [${missing}] extra: [${extra}]`);
  webBlock.base && TOKENS.every((t) => /^#[0-9a-f]{6}$/.test(webBlock.base[t] || ""))
    ? ok(`(a) a base html { } fallback rule (from :root) precedes the theme rules`)
    : bad(`(a) no complete base html { } fallback rule in the block`);
  const mixRule = web.match(/html \{\n((?:\s*--ink-[a-z]+: color-mix\(in srgb, var\(--[a-z]+\) 60%, var\(--text\) 40%\);\n)+)\}/);
  mixRule && (mixRule[1].match(/--ink-/g) || []).length === 5
    ? ok(`(a) the live html { --ink-*: color-mix(...) } rule is still present with all 5 tokens`)
    : bad(`(a) the html { --ink-*: color-mix(...) } rule is missing or incomplete`);
  (web.match(/--ink-[a-z]+: color-mix\(/g) || []).length === 5
    ? ok(`(a) exactly 5 color-mix --ink-* declarations in web/ (the twin lives in one rule, not duplicated per theme)`)
    : bad(`(a) ${(web.match(/--ink-[a-z]+: color-mix\(/g) || []).length} color-mix --ink-* declarations in web/ (want 5)`);
}
if (webBlock && distBlock) {
  distBlock.text === webBlock.text
    ? ok(`(a) dist/guidon-standalone.html carries the byte-identical fallback block`)
    : bad(`(a) dist/guidon-standalone.html fallback block differs from web/'s`);
}

/* ---- browser parts ---- */
const { server, url } = await serve("web");
const browser = await chromium.launch();
const context = await browser.newContext();
const page = await context.newPage();
const noise = [];
page.on("pageerror", (e) => noise.push("pageerror: " + e.message));
await page.goto(url, { waitUntil: "load" });
await dismissOnboarding(page, { mode: "guest" });

/* (e) the measurement: a custom property keeps its LAST declaration even
   when that value is an unknown function - declaration-level fallback does
   not exist for custom properties. */
const principle = await page.evaluate(() => {
  const st = document.createElement("style");
  st.textContent = "html { --gfx-probe: #ff0000; --gfx-probe: bogus-fn(1); } #gfx-probe { color: var(--gfx-probe); }";
  document.head.appendChild(st);
  const el = document.createElement("span"); el.id = "gfx-probe"; el.textContent = "x";
  document.body.appendChild(el);
  const out = { token: getComputedStyle(document.documentElement).getPropertyValue("--gfx-probe").trim(), color: getComputedStyle(el).color };
  el.remove(); st.remove();
  return out;
});
principle.token === "bogus-fn(1)"
  ? ok(`(e) measured: a custom property takes its LAST declaration even when unparseable as a colour (--gfx-probe = "${principle.token}", element color ${principle.color}, not #ff0000) - hence @supports, not two declarations`)
  : bad(`(e) unexpected custom-property behaviour: --gfx-probe = "${principle.token}"`);

/* (b)+(c)+(d): per theme, resolved tokens + rendered ink colours. */
const themeApi = await page.evaluate(() => !!(window.G && window.G.theme && typeof window.G.theme.applyTheme === "function"));
if (!themeApi) bad("G.theme.applyTheme is not available - cannot switch themes");
const parseCss = (s) => {
  let m = /^rgba?\((\d+),\s*(\d+),\s*(\d+)/.exec(s);
  if (m) return [+m[1], +m[2], +m[3]];
  m = /^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)/.exec(s);
  if (m) return [m[1], m[2], m[3]].map((v) => Math.round(+v * 255));
  return null;
};
const parseHex = (h) => { const m = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(h.trim()); return m ? [1, 2, 3].map((i) => parseInt(m[i], 16)) : null; };
const parseAny = (s) => parseHex(s) || parseCss(s) || (/^#([0-9a-f])([0-9a-f])([0-9a-f])$/i.test(s.trim()) ? s.trim().slice(1).split("").map((c) => parseInt(c + c, 16)) : null);
const blend = (a, t) => a.map((v, i) => Math.round(0.6 * v + 0.4 * t[i]));
const within1 = (x, y) => x && y && x.every((v, i) => Math.abs(v - y[i]) <= 1);
const hex = (c) => "#" + c.map((v) => v.toString(16).padStart(2, "0")).join("");

let cMismatch = [], dMismatch = [], measured = 0;
const bSamples = [];
for (const id of registryIds) {
  const r = await page.evaluate((id) => {
    window.G.theme.applyTheme(id);
    const cs = getComputedStyle(document.documentElement);
    const raw = {};
    for (const t of ["amber", "green", "red", "cyan", "violet", "text"]) raw[t] = cs.getPropertyValue("--" + t).trim();
    const ink = {};
    const rendered = {};
    for (const t of ["amber", "green", "red", "cyan", "violet"]) {
      ink[t] = cs.getPropertyValue("--ink-" + t).trim();
      const el = document.createElement("span"); el.style.color = "var(--ink-" + t + ")"; el.textContent = "x";
      document.body.appendChild(el); rendered[t] = getComputedStyle(el).color; el.remove();
    }
    return { theme: document.documentElement.getAttribute("data-theme"), light: document.documentElement.classList.contains("light"), raw, ink, rendered };
  }, id);
  if (r.theme !== id) { bad(`theme ${id} did not apply (data-theme=${r.theme})`); continue; }
  if (["night-vision", "field-manual", "ink-paper"].includes(id)) bSamples.push({ id, ink: r.ink.amber });
  const gen = webBlock && webBlock.rules[id];
  if (!gen) continue;
  const text = parseAny(r.raw.text);
  for (const t of TOKENS) {
    const accent = parseAny(r.raw[t]);
    const expected = accent && text ? blend(accent, text) : null;
    const staticHex = parseHex(gen[t] || "");
    measured++;
    if (!within1(expected, staticHex)) cMismatch.push(`${id}/${t}: engine tokens ${r.raw[t]} + ${r.raw.text} -> ${expected ? hex(expected) : "?"} vs generated ${gen[t]}`);
    const rendered = parseCss(r.rendered[t]);
    if (!within1(rendered, staticHex)) dMismatch.push(`${id}/${t}: rendered ${r.rendered[t]} vs generated ${gen[t]}`);
  }
}
for (const s of bSamples) {
  /color-mix\(/.test(s.ink) && !/^#/.test(s.ink)
    ? ok(`(b) ${s.id}: --ink-amber computes to the color-mix form (${s.ink.slice(0, 60)}), not the static hex`)
    : bad(`(b) ${s.id}: --ink-amber = "${s.ink}"`);
}
if (webBlock) {
  cMismatch.length === 0 && measured === 120
    ? ok(`(c) independent blend of the engine-resolved tokens matches every generated static hex within 1 per channel (${measured} of 24 x 5)`)
    : bad(`(c) ${cMismatch.length} blend mismatch(es) of ${measured}: ${cMismatch.slice(0, 4).join(" | ")}`);
  dMismatch.length === 0 && measured === 120
    ? ok(`(d) Chromium's own color-mix() rendering of var(--ink-*) matches the static hex within 1 per channel, all 24 themes`)
    : bad(`(d) ${dMismatch.length} rendered mismatch(es): ${dMismatch.slice(0, 4).join(" | ")}`);
}

/* (f) the boot notice: stub CSS.supports for the color-mix query only. */
const NOTICE = /older than GUIDON's engine floor/;
const plainToast = await page.evaluate(() => (document.getElementById("toast") || {}).textContent || "");
!NOTICE.test(plainToast) ? ok(`(f) no engine-floor notice on an engine that has color-mix (toast: "${plainToast.slice(0, 40)}")`) : bad(`(f) engine-floor notice shown on an engine that supports color-mix`);

const stubbed = await context.newPage();
stubbed.on("pageerror", (e) => noise.push("pageerror(stubbed): " + e.message));
await stubbed.addInitScript(() => {
  const real = CSS.supports.bind(CSS);
  CSS.supports = function (a, b) { if (/color-mix\(/.test(String(b) + String(a))) return false; return b === undefined ? real(a) : real(a, b); };
});
await stubbed.goto(url, { waitUntil: "load" });
const stubGuest = stubbed.locator(".ob-mode-card", { hasText: /guest session/i }).first();
await stubGuest.waitFor({ state: "visible", timeout: 8000 });
// First boot: the onboarding overlay (.ob-overlay, z-index 9000) sits over
// #toast (z-index 50), so a notice fired while it is up is invisible for its
// whole 9 s (measured: elementFromPoint at the toast centre = #ob-overlay).
// The notice must therefore be WITHHELD while #ob-overlay exists and fire
// once it is gone - polled here for 3 s (the notice's own delay is 1.2 s).
let early = "";
for (let i = 0; i < 20 && !NOTICE.test(early); i++) {
  await stubbed.waitForTimeout(150);
  early = await stubbed.evaluate(() => { const t = document.getElementById("toast"); const ob = document.getElementById("ob-overlay"); return ob && t && t.classList.contains("show") ? t.textContent : ""; });
}
!NOTICE.test(early)
  ? ok(`(f) notice withheld while the onboarding overlay is up (3 s, #ob-overlay present, toast not shown)`)
  : bad(`(f) notice fired behind the onboarding overlay (z-index 9000 over #toast's 50) where nobody can see it: "${early}"`);
if (await stubGuest.count()) await stubGuest.click();
let noticeText = "";
for (let i = 0; i < 40 && !NOTICE.test(noticeText); i++) {
  await stubbed.waitForTimeout(150);
  noticeText = await stubbed.evaluate(() => { const t = document.getElementById("toast"); return t && t.classList.contains("show") ? t.textContent : ""; });
}
NOTICE.test(noticeText)
  ? ok(`(f) engine floor notice shown via util.toast when CSS.supports denies color-mix: "${noticeText}"`)
  : bad(`(f) no engine-floor notice within 6s of boot with CSS.supports stubbed (toast: "${noticeText}")`);
/Chromium \d+ \/ WebKit [\d.]+ \/ Firefox \d+/.test(noticeText)
  ? ok(`(f) the notice names the floor from window.GUIDON_ENGINE_FLOOR (stamped by build.mjs from tools/engine-floor.json)`)
  : bad(`(f) the notice does not name the three engine floors: "${noticeText}"`);
const stamped = await stubbed.evaluate(() => JSON.stringify(window.GUIDON_ENGINE_FLOOR || null));
const floorJson = JSON.parse(await readFile("tools/engine-floor.json", "utf8"));
const stampedObj = JSON.parse(stamped);
stampedObj && stampedObj.chromium === floorJson.chromium && String(stampedObj.webkit) === String(floorJson.webkit) && stampedObj.gecko === floorJson.gecko && stampedObj.webview === floorJson.webview
  ? ok(`(f) window.GUIDON_ENGINE_FLOOR in web/ equals tools/engine-floor.json (${stamped})`)
  : bad(`(f) window.GUIDON_ENGINE_FLOOR = ${stamped}, tools/engine-floor.json = ${JSON.stringify(floorJson)}`);
await stubbed.close();

noise.length === 0 ? ok("no page errors") : bad("page errors: " + noise.slice(0, 4).join(" | "));

await browser.close();
await server.close();
console.log(fails ? "\nINK-FALLBACKS: " + fails + " FAILURE(S)" : "\nINK-FALLBACKS: all passed");
process.exit(fails ? 1 : 0);
